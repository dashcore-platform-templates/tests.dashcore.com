<?php

namespace Dashcore\DesignKit;

/**
 * The stylesheet a built-in style ships in this package, imported from vendor/:
 *
 *     @import 'tailwindcss';
 *     @import '../../vendor/dashcore/design-kit/dist/dashcore.css';
 *     @source '../../vendor/dashcore/design-kit/resources/views';
 *
 * Where design:apply writes a design's tokens into an app's own app.css, a
 * style is read from the package on every build. That is the whole difference,
 * and it is why a style can change across the fleet with a release: nothing in
 * the app holds a copy that would have to be re-applied.
 *
 * Built by design.dashcore.com from the same resolver and contrast check every
 * design goes through (`php artisan design:build-styles` there), and committed,
 * because the package is published as a subtree and has no build step of its
 * own.
 *
 * The @source line stays in the app. Tailwind resolves it against the file that
 * says it, and only the app's app.css knows where vendor/ is.
 */
final class Stylesheet
{
    /**
     * @param  array<string,mixed>  $tokens  A style's tokens, in the shape a design file's tokens take.
     */
    public static function build(string $name, array $tokens): string
    {
        $sans = $tokens['fonts']['sans'];
        $second = $tokens['fonts']['second'];

        $lines = [
            "/* dashcore/design-kit: the {$name} style. Generated by design.dashcore.com; do not edit. */",
            '',
            // Light on :root; dark three ways, because the fleet already uses all
            // three: the OS preference, a dark class (Flux, Breeze) and
            // data-theme. An explicit light choice beats the OS.
            ':root { '.self::register($tokens, 'light').' color-scheme: light; }',
            '@media (prefers-color-scheme: dark) {',
            "    :root:not(.light):not([data-theme='light']) { ".self::register($tokens, 'dark').' color-scheme: dark; }',
            '}',
            ":root.dark, :root[data-theme='dark'] { ".self::register($tokens, 'dark').' color-scheme: dark; }',
            '',
            '@theme {',
        ];

        foreach ($tokens['neutral'] as $step => $hex) {
            $lines[] = "    --color-zinc-{$step}: {$hex};";
        }
        $lines[] = "    --font-sans: '{$sans['family']}', {$sans['fallback']};";
        $lines[] = "    --font-second: '{$second['family']}', {$second['fallback']};";
        if (($second['kind'] ?? null) === 'mono') {
            $lines[] = "    --font-mono: '{$second['family']}', {$second['fallback']};";
        } else {
            // dashcore/ui called the serif face font-display, and views use it.
            $lines[] = "    --font-display: '{$second['family']}', {$second['fallback']};";
        }
        foreach ($tokens['radius'] as $step => $px) {
            $lines[] = "    --radius-{$step}: {$px};";
        }
        $lines[] = '}';

        // Flux reads the accent from these. Pointed at the roles rather than at
        // hex values, so they switch with the register on the same element.
        $lines[] = '@layer base {';
        $lines[] = '    :root { --color-accent: var(--ds-accent); --color-accent-content: var(--ds-accent-content); --color-accent-foreground: var(--ds-on-accent); }';
        $lines[] = '}';
        $lines[] = '';

        array_push($lines, ...Applier::utilities());

        if (isset($tokens['radius_ceiling'])) {
            $ceiling = $tokens['radius_ceiling'];
            $lines[] = '';
            // rounded-full is not a theme variable in Tailwind 4, it compiles to a
            // literal, so the radius variables above cannot reach it. A radio and
            // a switch keep their shape because the shape is what they mean.
            $lines[] = "/* 14: a {$ceiling} ceiling, rounded-full included. */";
            $lines[] = '@layer utilities {';
            $lines[] = "    .rounded-full:not([data-flux-radio-indicator], [data-flux-radio-indicator] *, [data-flux-switch], [data-flux-switch] *) { border-radius: {$ceiling}; }";
            $lines[] = '    .ds-circle { border-radius: 50%; }';
            $lines[] = '}';
        }

        array_push($lines, ...Applier::fluxCorrections());

        // The frame x-ds::shell draws with, and dashcore/ui's dc-* names.
        $lines[] = '';
        $lines[] = rtrim((string) file_get_contents(dirname(__DIR__).'/resources/css/frame.css'));

        return implode("\n", $lines)."\n";
    }

    /**
     * One register's custom properties: density, roles and status.
     *
     * @param  array<string,mixed>  $tokens
     */
    private static function register(array $tokens, string $register): string
    {
        $out = [];
        foreach ($tokens['density'] as $name => $px) {
            $out[] = "--ds-{$name}: {$px};";
        }
        foreach ($tokens[$register] as $role => $hex) {
            $out[] = "--ds-{$role}: {$hex};";
        }
        foreach ($tokens['status'] as $name => $s) {
            $out[] = "--ds-{$name}: {$s["text-{$register}"]}; --ds-{$name}-fill: {$s['fill']}; --ds-{$name}-soft: {$s["soft-{$register}"]};";
        }
        // 02: the sidebar is sunken in light and surface in dark.
        $out[] = '--ds-sidebar: '.$tokens[$register][$register === 'dark' ? 'surface' : 'sunken'].';';
        if ($register === 'dark') {
            // 04's dark muted correction: Flux's zinc-500 fails on zinc-800.
            $out[] = "--color-zinc-500: {$tokens['neutral'][400]};";
        }

        return implode(' ', $out);
    }
}
