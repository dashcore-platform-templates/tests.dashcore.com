<?php

namespace Dashcore\DesignKit;

use InvalidArgumentException;

/**
 * Turns a design file into file changes for a kit. Pure: every method takes
 * strings and arrays and returns strings and arrays, so it can be tested
 * without a Laravel app. The command owns reading and writing.
 *
 * What it changes, from standard/09:
 *  - resources/css/app.css: a block between marker comments with the Flux
 *    theme variables, the --ds-* roles, and the dark muted-text correction.
 *  - vite.config.js: the Bunny font entries for the pairing.
 *  - .env: the sign-in copy and the decisions the components need.
 *  - resources/views/layouts/auth.blade.php: points at the two-panel layout.
 *  - the four Lucide-named icon overrides the kit ships: deleted.
 */
final class Applier
{
    public const START = '/* dashcore-design:start (generated by design:apply, do not edit by hand) */';

    public const END = '/* dashcore-design:end */';

    public const LUCIDE_ICONS = [
        'resources/views/flux/icon/book-open-text.blade.php',
        'resources/views/flux/icon/chevrons-up-down.blade.php',
        'resources/views/flux/icon/folder-git-2.blade.php',
        'resources/views/flux/icon/layout-grid.blade.php',
    ];

    /**
     * The Tailwind families Flux paints a callout from, by the status each
     * one says. A family not listed, violet or zinc, is not a status and is
     * left as Flux draws it.
     */
    public const CALLOUT_FAMILIES = [
        'danger' => ['red', 'rose'],
        'warning' => ['yellow', 'amber', 'orange'],
        'success' => ['green', 'emerald', 'lime'],
        'info' => ['blue', 'sky'],
    ];

    /** The Heroicon that stands in for each Lucide name the kit uses. */
    public const LUCIDE_RENAMES = [
        'book-open-text' => 'book-open',
        'chevrons-up-down' => 'chevron-up-down',
        'folder-git-2' => 'folder',
        'layout-grid' => 'squares-2x2',
    ];

    /**
     * Swap Lucide icon names for Heroicons wherever a Blade file names one:
     * icon="name", icon: 'name', or <flux:icon.name. Deleting the override
     * files without this breaks the kit's own sidebar.
     */
    /**
     * Lines the Laravel starter kit ships that are off the standard, and the
     * exact line each becomes.
     *
     * Every kit in the fleet starts from the same starter kit, so these arrive
     * identical in every one: the same greys in the same components, the same
     * green for a saved confirmation, the same off-scale margin. They were
     * fixed by hand three times in three apps before this existed, with the
     * same answer each time, which is the definition of something the adapter
     * should do once.
     *
     * Matched byte for byte on purpose. An app that has touched one of these
     * lines has made a decision, and a decision is not drift: the match fails
     * and the line is left for the audit to report and a person to judge.
     *
     * Only the mechanical half is here. A grey becoming text-muted has one
     * right answer. Whether an underlined link should have been a button, or
     * which heading is a section heading, does not, and that work belongs to
     * whoever is reading the screen.
     *
     * @return array<string,string>
     */
    public static function starterKitFixes(): array
    {
        // The same focus ring and underline on a resend-verification control,
        // in two files, identical in both.
        $verifyButton = 'rounded-md text-sm text-gray-600 underline hover:text-gray-900 focus:outline-hidden focus:ring-2 focus:ring-indigo-500 focus:ring-offset-2';
        $verifyButtonFixed = 'rounded-md text-sm text-(--ds-text-muted) underline hover:text-(--ds-text) focus:outline-hidden focus:ring-2 focus:ring-(--ds-accent) focus:ring-offset-2';

        return [
            // A saved-confirmation line is secondary text.
            "'class' => 'text-sm text-gray-600'" => "'class' => 'text-sm text-(--ds-text-muted)'",

            // Green here means one thing: it worked.
            "'class' => 'font-medium text-sm text-green-600'" => "'class' => 'text-sm font-medium text-(--ds-success)'",

            // 05: the scale is 1 2 3 4 6 8 12 16. Ten is on neither end of it.
            'class="mr-10 w-full pb-4 md:w-[220px]"' => 'class="mr-8 w-full pb-4 md:w-[220px]"',

            'class="text-center text-sm text-gray-600"' => 'class="text-center text-sm text-(--ds-text-muted)"',
            'class="font-medium text-center text-sm text-green-600"' => 'class="text-center text-sm font-medium text-(--ds-success)"',
            'class="mt-2 text-sm text-gray-800"' => 'class="mt-2 text-sm text-(--ds-text)"',
            'class="mt-2 text-sm font-medium text-green-600"' => 'class="mt-2 text-sm font-medium text-(--ds-success)"',

            "class=\"{$verifyButton}\"" => "class=\"{$verifyButtonFixed}\"",
        ];
    }

    /** Whether this file carries any starter-kit line the adapter can fix. */
    public static function hasStarterKitDrift(string $blade): bool
    {
        foreach (array_keys(self::starterKitFixes()) as $from) {
            if (str_contains($blade, $from)) {
                return true;
            }
        }

        return false;
    }

    /** The same file with those lines on the roles. Running it twice changes nothing. */
    public static function fixStarterKit(string $blade): string
    {
        return str_replace(array_keys(self::starterKitFixes()), array_values(self::starterKitFixes()), $blade);
    }

    public static function renameLucide(string $blade): string
    {
        foreach (self::LUCIDE_RENAMES as $lucide => $hero) {
            $blade = str_replace(
                ["\"{$lucide}\"", "'{$lucide}'", "flux:icon.{$lucide}"],
                ["\"{$hero}\"", "'{$hero}'", "flux:icon.{$hero}"],
                $blade,
            );
        }

        return $blade;
    }

    /** True when a Blade file mentions any of the Lucide names. */
    public static function mentionsLucide(string $blade): bool
    {
        foreach (array_keys(self::LUCIDE_RENAMES) as $lucide) {
            if (str_contains($blade, $lucide)) {
                return true;
            }
        }

        return false;
    }

    /**
     * @param  array<string,mixed>  $design  The decoded design.json.
     * @return array<string,mixed> The tokens layer, validated.
     */
    public static function tokens(array $design): array
    {
        if (($design['schema'] ?? null) !== 'dashcore-design/1') {
            throw new InvalidArgumentException('Not a dashcore-design/1 file.');
        }
        $tokens = $design['tokens'] ?? null;
        if (! is_array($tokens) || ! isset($tokens['light'], $tokens['dark'], $tokens['neutral'], $tokens['fonts'], $tokens['radius'])) {
            throw new InvalidArgumentException('The file has no tokens layer. Export it from design.dashcore.com rather than writing it by hand.');
        }

        return $tokens;
    }

    /**
     * The CSS block. Appended after the kit's own @theme so later declarations
     * win; the .dark rules sit in the theme layer like the kit's own.
     *
     * @param  array<string,mixed>  $tokens
     */
    public static function cssBlock(array $tokens): string
    {
        $sans = $tokens['fonts']['sans'];
        $second = $tokens['fonts']['second'];
        $l = $tokens['light'];
        $d = $tokens['dark'];

        $lines = [
            self::START,
            // Tailwind only generates classes it sees. The kit scans its own views;
            // the package's components and sign-in layout live in vendor.
            "@source '../../vendor/dashcore/design-kit/resources/views';",
            '@theme {',
        ];
        foreach ($tokens['neutral'] as $step => $hex) {
            $lines[] = "    --color-zinc-{$step}: {$hex};";
        }
        $lines[] = "    --color-accent: {$l['accent']};";
        $lines[] = "    --color-accent-content: {$l['accent-content']};";
        $lines[] = "    --color-accent-foreground: {$l['on-accent']};";
        $lines[] = "    --font-sans: '{$sans['family']}', {$sans['fallback']};";
        $lines[] = "    --font-second: '{$second['family']}', {$second['fallback']};";
        if (($second['kind'] ?? null) === 'mono') {
            $lines[] = "    --font-mono: '{$second['family']}', {$second['fallback']};";
        }
        foreach ($tokens['radius'] as $step => $px) {
            $lines[] = "    --radius-{$step}: {$px};";
        }
        $lines[] = '}';

        // Dark accent, and the muted-text correction from standard/04: Flux uses
        // zinc-500 for muted text in dark, which fails 4.5:1 on zinc-800.
        $lines[] = '@layer theme {';
        $lines[] = '    .dark {';
        $lines[] = "        --color-accent: {$d['accent']};";
        $lines[] = "        --color-accent-content: {$d['accent-content']};";
        $lines[] = "        --color-accent-foreground: {$d['on-accent']};";
        $lines[] = "        --color-zinc-500: {$tokens['neutral'][400]};";
        $lines[] = '    }';
        $lines[] = '}';

        $lines[] = ':root { '.self::roles($tokens, 'light').' }';
        $lines[] = '.dark { '.self::roles($tokens, 'dark').' }';

        array_push($lines, ...self::utilities(), ...self::fluxCorrections());

        $lines[] = self::END;

        return implode("\n", $lines);
    }

    /**
     * The label and second-face utilities from 03. Shared by the block written
     * into a kit and the stylesheet a style ships from vendor/.
     *
     * @return list<string>
     */
    public static function utilities(): array
    {
        $lines = [];
        $lines[] = '@utility font-second { font-family: var(--font-second); }';
        $lines[] = '@utility ds-label { font-size: 12px; line-height: 1.33; font-weight: 500; letter-spacing: 0.04em; color: var(--ds-text-muted); }';
        $lines[] = '@utility ds-eyebrow { font-size: 12px; line-height: 1.33; font-weight: 500; letter-spacing: 0.08em; text-transform: uppercase; color: var(--ds-text-muted); font-family: var(--font-mono); }';

        return $lines;
    }

    /**
     * 06 brought onto Flux where Flux ships something else: the table, and the
     * danger button. These sit outside any @layer, which beats Tailwind's
     * utilities without !important, because unlayered styles win over layered
     * ones.
     *
     * @return list<string>
     */
    public static function fluxCorrections(): array
    {
        $lines = [];
        // The Flux table, brought onto 06. Flux ships a 14px head in body colour
        // with no fill; the standard wants sunken, 12px, muted. Every app using
        // flux:table drifts the same way, so the correction belongs here rather
        // than on each screen, the same argument the badge override rests on.
        //
        // These rules sit outside any @layer, which beats Tailwind's utilities
        // without !important, because unlayered styles win over layered ones.
        $lines[] = '';
        $lines[] = '/* 06: the table head sits on sunken, 12px, muted. */';
        $lines[] = '[data-flux-table] thead [data-flux-column] {';
        $lines[] = '    background: var(--ds-sunken);';
        $lines[] = '    font-size: 12px;';
        $lines[] = '    line-height: 1.33;';
        $lines[] = '    font-weight: 500;';
        $lines[] = '    color: var(--ds-text-muted);';
        $lines[] = '    border-bottom-color: var(--ds-border);';
        $lines[] = '}';
        $lines[] = '/* Body rows on surface, 14px, one pixel border, row height from density. */';
        $lines[] = '[data-flux-table] tbody [data-flux-cell] {';
        $lines[] = '    font-size: 14px;';
        $lines[] = '    color: var(--ds-text);';
        $lines[] = '    height: var(--ds-row);';
        $lines[] = '    border-bottom-color: var(--ds-border);';
        $lines[] = '    font-variant-numeric: tabular-nums;';
        $lines[] = '}';
        $lines[] = '/* 06: the first column identifies the row, so it carries text-strong. */';
        $lines[] = '[data-flux-table] tbody [data-flux-cell]:first-child {';
        $lines[] = '    color: var(--ds-text-strong);';
        $lines[] = '    font-weight: 500;';
        $lines[] = '}';
        $lines[] = '[data-flux-table] tbody tr:hover [data-flux-cell] {';
        $lines[] = '    background: var(--ds-sunken);';
        $lines[] = '}';

        // 06's danger button is an outline, and Flux's is a solid red fill. Flux
        // marks the variant only by its fill class, so that class is the hook;
        // a screen keeps writing variant="danger" and the outline arrives here.
        $lines[] = '/* 06: a destructive action is an outline, never a red fill. */';
        $lines[] = '[data-flux-button].bg-red-500 {';
        $lines[] = '    background: transparent;';
        $lines[] = '    color: var(--ds-danger);';
        $lines[] = '    border: 1px solid var(--ds-danger);';
        $lines[] = '    box-shadow: none;';
        $lines[] = '}';
        $lines[] = '[data-flux-button].bg-red-500:hover {';
        $lines[] = '    background: var(--ds-danger-soft);';
        $lines[] = '}';

        // 06's callout is soft and in the status colours, and Flux paints each
        // variant from a Tailwind family through --callout-* properties. Flux
        // marks the family only in those property classes, so its 50 step is
        // the hook. The treatment is the flash's: the soft tint and a two pixel
        // rule in the status colour, body text in text. Warning arrives as
        // yellow, and an app that set color= by hand reaches the same four.
        $lines[] = '/* 06: a callout takes the status roles, the flash\'s treatment. */';
        foreach (self::CALLOUT_FAMILIES as $status => $families) {
            $selectors = implode(', ', array_map(fn (string $family): string => "[data-flux-callout][class*='var(--color-{$family}-50)']", $families));
            $lines[] = "{$selectors} {";
            $lines[] = "    --callout-background: var(--ds-{$status}-soft);";
            $lines[] = "    --callout-border: var(--ds-{$status});";
            $lines[] = "    --callout-heading: var(--ds-{$status});";
            $lines[] = '    --callout-text: var(--ds-text);';
            $lines[] = "    --callout-icon: var(--ds-{$status});";
            $lines[] = '    border-color: transparent;';
            $lines[] = "    border-inline-start: 2px solid var(--ds-{$status});";
            $lines[] = '    border-radius: var(--radius-sm);';
            $lines[] = '}';
        }


        return $lines;
    }

    /** The lines a style puts in an app's app.css, straight after Tailwind. */
    public static function styleLines(string $name): string
    {
        return "@import '../../vendor/dashcore/design-kit/dist/{$name}.css';\n@source '../../vendor/dashcore/design-kit/resources/views';";
    }

    /**
     * An app's app.css, taking a style from vendor/ rather than a copy of a
     * design's tokens.
     *
     * The applied block goes, because the stylesheet carries all of it and two
     * sets of the same variables would leave the order of the file to decide.
     * dashcore/ui's import and source lines go too: the style replaces them,
     * and leaving them would load two definitions of every dc-* name. Lines
     * already there are left where they are, so applying twice is a no-op.
     */
    public static function applyStyleCss(string $css, string $name): string
    {
        $start = strpos($css, self::START);
        $end = strpos($css, self::END);
        if ($start !== false && $end !== false && $end > $start) {
            $css = substr($css, 0, $start).ltrim(substr($css, $end + strlen(self::END)), "\n");
        }

        $css = (string) preg_replace('#^\s*@(import|source)\s+[\'"][^\'"]*vendor/dashcore/ui/[^\'"]*[\'"]\s*;\s*\n?#m', '', $css);
        // A different style's import, when an app moves from one to another.
        $css = (string) preg_replace('#^\s*@import\s+[\'"][^\'"]*vendor/dashcore/design-kit/dist/(?!'.preg_quote($name, '#').'\.css)[^\'"]*[\'"]\s*;\s*\n?#m', '', $css);

        $wanted = self::styleLines($name);
        $missing = array_values(array_filter(explode("\n", $wanted), fn (string $line) => ! str_contains($css, $line)));
        if ($missing === []) {
            return $css;
        }

        $insert = implode("\n", $missing);
        if (preg_match('#^@import\s+[\'"]tailwindcss[\'"]\s*;[^\n]*\n#m', $css, $m, PREG_OFFSET_CAPTURE)) {
            $at = $m[0][1] + strlen($m[0][0]);

            return substr($css, 0, $at).$insert."\n".substr($css, $at);
        }

        return "@import 'tailwindcss';\n".$insert."\n".ltrim($css);
    }

    /**
     * The app's app.js, taking the frame's script: Escape closes the drawer and
     * the theme toggle remembers its choice. dashcore/ui's import becomes it.
     */
    public static function applyStyleJs(string $js): string
    {
        $line = "import '../../vendor/dashcore/design-kit/resources/js/frame.js';";
        $js = (string) preg_replace('#^[ \t]*import\s+[\'"][^\'"]*vendor/dashcore/ui/resources/js/ui\.js[\'"][ \t]*;?[ \t]*$#m', $line, $js);

        return str_contains($js, $line) ? $js : rtrim($js)."\n".$line."\n";
    }

