    {
        $second = $tokens['fonts']['second'] ?? [];

        return [
            'DESIGN_MOTIF' => $motif,
            'DESIGN_SECOND_KIND' => (string) ($second['kind'] ?? 'mono'),
            'DESIGN_CONDENSED' => ! empty($second['condensed']) ? 'true' : 'false',
